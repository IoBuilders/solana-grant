// Every problem is reported in one run: cataloguing a bounded context with forty events should
// not take forty generations.
func TestResolveMessagesReportsEveryProblemAtOnce(t *testing.T) {
	_, err := resolveMessages(spec{bc: "dltingress"}, []discovered{
		{goType: "transaction.FirstEvent", typeName: "FirstEvent", publishers: []string{"a command handler"}},
		{goType: "transaction.SecondEvent", typeName: "SecondEvent", publishers: []string{"b command handler"}},
	})

	require.Error(t, err)
	assert.Contains(t, err.Error(), "transaction.FirstEvent")
	assert.Contains(t, err.Error(), "transaction.SecondEvent")
}

