// Two events whose type names differ only by package would overwrite each other in
// components.messages, so the collision is reported instead.
func TestResolveMessagesRejectsCollidingNames(t *testing.T) {
	s := spec{
		bc: "dltingress",
		docs: []doc{
			{event: transaction.RetriedEvent{}},
			{event: coreRetried{}},
		},
	}

	found := []discovered{
		{goType: "transaction.RetriedEvent", typeName: "RetriedEvent", aggregate: "transaction", publishers: []string{"a"}},
		{goType: "main.coreRetried", typeName: "RetriedEvent", aggregate: "process", publishers: []string{"b"}},
	}

	_, err := resolveMessages(s, found)

	require.Error(t, err)
	assert.Contains(t, err.Error(), "resolve to the message name")
}

// coreRetried stands in for a second RetriedEvent declared in another package; only its type
// identity matters to the collision check.
type coreRetried struct {
	event.BaseEvent
}

// Derived operations: the summaries name the producers and consumers discovery found, and an
// orphan gets no receive operation at all.
func TestBuildOperationsDerivesSummaries(t *testing.T) {
	messages := []message{
		{
			name:       "KeyCreated",
			channel:    "keyCreated",
			publishers: []string{"createkey command handler"},
			consumers:  []string{"keycreatedlistener.Listener"},
			doc:        doc{receiveNote: "That listener republishes it on the cross bus."},
		},
		{name: "Saved", channel: "saved", publishers: []string{"savefailedtransaction command handler"}},
	}

	operations := buildOperations(messages)

	assert.Equal(t, "Published by the createkey command handler.", operations["sendKeyCreated"].Summary)
	assert.Equal(t,
		"Consumed by keycreatedlistener.Listener. That listener republishes it on the cross bus.",
		operations["receiveKeyCreated"].Summary,
	)
	assert.Equal(t,
		"Published by the savefailedtransaction command handler. No bounded context currently consumes it.",
		operations["sendSaved"].Summary,
	)
	assert.NotContains(t, operations, "receiveSaved")
}

